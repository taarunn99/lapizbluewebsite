/**
 * Coverage report.
 *
 * Reconciles what Lapiz Blue actually stocks against what was harvested from
 * the manufacturer, and writes data/discovery/COVERAGE.md.
 *
 * The point is to make "nothing is missing" checkable instead of asserted.
 * Every stocked product is either matched to a harvested catalogue entry with
 * an image, or it is named in the report as unmatched so it can be dealt with
 * by hand.
 *
 * Usage: npx tsx scripts/coverage-report.ts --brand vetonit
 */

import fs from 'node:fs';
import path from 'node:path';
import { slugify } from '../src/lib/slugify';

interface StockItem {
  category: string;
  name: string;
  description: string;
  pack: string;
}

interface Harvested {
  source_slug: string;
  name: string;
  source_category: string;
  image_url: string;
  tds_url: string;
  sds_url: string;
  product_url: string;
  uses: string[];
  usage: Record<string, string>;
}

const brand = (() => {
  const i = process.argv.indexOf('--brand');
  return i === -1 ? 'vetonit' : process.argv[i + 1];
})();

const DIR = path.join(process.cwd(), 'data', 'discovery');
const stock: { products: StockItem[] } = JSON.parse(
  fs.readFileSync(path.join(DIR, `${brand}-stocklist.json`), 'utf8'),
);
const harvest: { products: Harvested[] } = JSON.parse(
  fs.readFileSync(path.join(DIR, `${brand}.json`), 'utf8'),
);

/** Compare on letters and digits only, so spacing and case cannot cause a miss. */
const key = (s: string) => s.toLowerCase().replace(/[^a-z0-9]/g, '');
/** Product codes carry the identity: "Vetoset CA545" -> "ca545". */
const code = (s: string) => {
  const m = s.match(/\b([a-z]{1,3}\s?\d{2,4})\b/i);
  return m ? m[1].toLowerCase().replace(/\s/g, '') : '';
};

const byKey = new Map<string, Harvested>();
const byCode = new Map<string, Harvested>();
for (const h of harvest.products) {
  byKey.set(key(h.name), h);
  // The manufacturer suffixes regional duplicates, so strip a trailing -0.
  byKey.set(key(h.source_slug.replace(/-\d+$/, '')), h);
  const c = code(h.name);
  if (c && !byCode.has(c)) byCode.set(c, h);
}

type Row = { item: StockItem; hit?: Harvested; how: string };
const rows: Row[] = stock.products.map((item) => {
  const k = key(item.name);
  if (byKey.has(k)) return { item, hit: byKey.get(k), how: 'name' };
  const c = code(item.name);
  if (c && byCode.has(c)) return { item, hit: byCode.get(c), how: 'code' };
  // Last resort: the stocked name is a prefix of a catalogue name, or vice
  // versa. Reported separately so a human can sanity check the loose ones.
  const loose = harvest.products.find(
    (h) => key(h.name).startsWith(k) || k.startsWith(key(h.name)),
  );
  if (loose && k.length >= 8) return { item, hit: loose, how: 'prefix' };
  return { item, how: 'none' };
});

const matched = rows.filter((r) => r.hit);
const withImage = matched.filter((r) => r.hit!.image_url);
const withUsage = matched.filter((r) => Object.keys(r.hit!.usage).length > 0);
const unmatched = rows.filter((r) => !r.hit);

const byCategory = new Map<string, Row[]>();
for (const r of rows) {
  const list = byCategory.get(r.item.category) ?? [];
  list.push(r);
  byCategory.set(r.item.category, list);
}

const pct = (n: number, d: number) => (d === 0 ? '0' : Math.round((n / d) * 100).toString());

const lines: string[] = [];
lines.push(`# ${brand} coverage`);
lines.push('');
lines.push(
  `Generated by \`npx tsx scripts/coverage-report.ts --brand ${brand}\` on ${new Date().toISOString().slice(0, 10)}.`,
);
lines.push('');
lines.push(
  `Reconciles the ${stock.products.length} products Lapiz Blue stocks against the ` +
    `${harvest.products.length} found in the manufacturer catalogue.`,
);
lines.push('');
lines.push('| | Count | Share |');
lines.push('|---|---|---|');
lines.push(`| Stocked products | ${stock.products.length} | |`);
lines.push(`| Matched to a catalogue page | ${matched.length} | ${pct(matched.length, stock.products.length)}% |`);
lines.push(`| With an official product image | ${withImage.length} | ${pct(withImage.length, stock.products.length)}% |`);
lines.push(`| With technical detail harvested | ${withUsage.length} | ${pct(withUsage.length, stock.products.length)}% |`);
lines.push(`| **Unmatched, need attention** | **${unmatched.length}** | ${pct(unmatched.length, stock.products.length)}% |`);
lines.push('');

if (unmatched.length > 0) {
  lines.push('## Unmatched products');
  lines.push('');
  lines.push('These are stocked but no catalogue page was found. Each needs an image and');
  lines.push('technical detail from another source before its page can ship.');
  lines.push('');
  lines.push('| Product | Category | Pack |');
  lines.push('|---|---|---|');
  for (const r of unmatched) {
    lines.push(`| ${r.item.name} | ${r.item.category} | ${r.item.pack} |`);
  }
  lines.push('');
}

const loose = rows.filter((r) => r.how === 'prefix');
if (loose.length > 0) {
  lines.push('## Matched loosely, worth a human check');
  lines.push('');
  lines.push('| Stocked as | Matched to | Catalogue page |');
  lines.push('|---|---|---|');
  for (const r of loose) lines.push(`| ${r.item.name} | ${r.hit!.name} | ${r.hit!.product_url} |`);
  lines.push('');
}

lines.push('## By category');
lines.push('');
for (const [category, list] of byCategory) {
  const ok = list.filter((r) => r.hit).length;
  lines.push(`### ${category}`);
  lines.push('');
  lines.push(`${ok} of ${list.length} matched.`);
  lines.push('');
  lines.push('| Product | Pack | Match | Image | Detail |');
  lines.push('|---|---|---|---|---|');
  for (const r of list) {
    const h = r.hit;
    lines.push(
      `| ${r.item.name} | ${r.item.pack} | ${h ? r.how : 'none'} | ${h?.image_url ? 'yes' : 'no'} | ` +
        `${h && Object.keys(h.usage).length > 0 ? Object.keys(h.usage).length + ' blocks' : 'no'} |`,
    );
  }
  lines.push('');
}

lines.push('## Catalogue products not stocked');
lines.push('');
const stockedSlugs = new Set(matched.map((r) => r.hit!.source_slug));
const extra = harvest.products.filter((h) => !stockedSlugs.has(h.source_slug));
lines.push(
  `${extra.length} catalogue products are not on the stock list. They are not built as pages, ` +
    'but they are available if Lapiz Blue decides to carry them.',
);
lines.push('');
for (const h of extra) lines.push(`- ${h.name}`);
lines.push('');

const out = path.join(DIR, 'COVERAGE.md');
fs.writeFileSync(out, lines.join('\n'));

console.log(`${brand}: ${matched.length}/${stock.products.length} matched, ${withImage.length} with an image, ${unmatched.length} unmatched`);
console.log(`Report written to ${path.relative(process.cwd(), out)}`);
if (unmatched.length > 0) {
  console.log('\nUnmatched:');
  for (const r of unmatched) console.log(`  ${r.item.name}  (${r.item.category})`);
}
