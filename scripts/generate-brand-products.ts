/**
 * Emit the featuredProducts arrays for a brand from the manifest.
 *
 * brandConfigs.ts is static data compiled into client components, so it
 * cannot read the manifest at runtime: the manifest loader uses fs. This
 * writes the product lists out as a TypeScript module instead, so the
 * manifest stays the single source of truth for what exists and the brand
 * config stays the single source of truth for how it reads.
 *
 * Re-run it whenever products are added or renamed.
 *
 * Usage: npx tsx scripts/generate-brand-products.ts --brand vetonit
 */

import fs from 'node:fs';
import path from 'node:path';
import type { ManifestRecord } from '../src/lib/tds';
import { TDS_CATEGORY_LABELS } from '../src/lib/tds';

const arg = (f: string) => {
  const i = process.argv.indexOf(f);
  return i === -1 ? undefined : process.argv[i + 1];
};
const brand = arg('--brand') ?? 'vetonit';

const REPO = process.cwd();
const manifest: ManifestRecord[] = JSON.parse(
  fs.readFileSync(path.join(REPO, 'data', 'manifest.json'), 'utf8'),
);
const records = manifest.filter((r) => r.brand === brand);
if (records.length === 0) {
  console.error(`No manifest records for brand "${brand}".`);
  process.exit(1);
}

/** Escape for a single quoted TS string literal. */
const q = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

/**
 * The card blurb. Prefers the manufacturer's own one line product type, which
 * is what a buyer scanning a grid needs, and falls back to the category label
 * so a card is never blank.
 */
function blurb(rec: ManifestRecord): string {
  // House copy spells the conjunction out. The manufacturer uses ampersands.
  const type = rec.specs.product_type?.replace(/\s*&\s*/g, ' and ').replace(/\s+/g, ' ').trim();
  const pack = rec.specs.pack_size ? ` Supplied in ${rec.specs.pack_size.toLowerCase()}.` : '';
  if (type) return `${type.replace(/\.$/, '')}.${pack}`;
  return `${TDS_CATEGORY_LABELS[rec.category]} from the ${brand} range.${pack}`;
}

const byLine = new Map<string, ManifestRecord[]>();
for (const rec of records) {
  const list = byLine.get(rec.product_line) ?? [];
  list.push(rec);
  byLine.set(rec.product_line, list);
}

const lines: string[] = [];
lines.push('/* Generated by scripts/generate-brand-products.ts. Do not edit by hand. */');
lines.push("import type { FeaturedProduct } from '@/data/brandConfigs';");
lines.push('');
lines.push(`export const ${brand}Products: Record<string, FeaturedProduct[]> = {`);

for (const [line, list] of [...byLine.entries()].sort()) {
  // Stable order so a regeneration produces no spurious diff.
  list.sort((a, b) => a.name.localeCompare(b.name));
  lines.push(`  ${q(line)}: [`);
  for (const rec of list) {
    lines.push('    {');
    lines.push(`      name: ${q(rec.name)},`);
    lines.push(`      description: ${q(blurb(rec))},`);
    lines.push(`      image: ${q(rec.image.path)},`);
    lines.push(`      category: ${q(TDS_CATEGORY_LABELS[rec.category])},`);
    lines.push('    },');
  }
  lines.push('  ],');
}
lines.push('};');
lines.push('');

const outDir = path.join(REPO, 'src', 'data', 'brand-configs');
fs.mkdirSync(outDir, { recursive: true });
const out = path.join(outDir, `${brand}.products.ts`);
fs.writeFileSync(out, lines.join('\n'));

console.log(`${brand}: ${records.length} products across ${byLine.size} lines`);
for (const [line, list] of [...byLine.entries()].sort()) console.log(`  ${String(list.length).padStart(2)}  ${line}`);
console.log(`Written to ${path.relative(REPO, out)}`);
