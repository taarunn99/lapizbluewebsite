"use client";

import { useMemo, useState } from "react";
import { AnimatePresence, motion, useReducedMotion } from "framer-motion";
import catalogue from "@/data/fila-products.json";

/**
 * The FILA tool, built on the FILA Easy Guide Middle East 06.2023 as data.
 *
 * Tab one answers "what do I use": material and stage give the product, the
 * dilution the guide prints and the point in the programme, drawn as a timeline.
 * Tab two answers "how much do I need": area, product and coats or dilution give
 * litres and packs from the coverage figures on the product's own page.
 *
 * Every figure comes from src/data/fila-products.json, generated by
 * scripts/fila-catalogue.mjs from the guide. The data sheet governs on site.
 */

type Coverage = { surface: string; sqmPerLitre: number | number[]; note?: string };
type Product = {
  slug: string;
  name: string;
  category: "cleaner" | "protector" | "finish";
  ready: boolean;
  purpose: string;
  surfaces: string[];
  dilutions: { label: string; ratio: string; note?: string }[];
  coverage: Coverage[];
  packSizes: string[];
  page: number;
};
type Treatment = { material: string; stage: Stage; product: string; dilution: string; note: string };
type Stage = "after installation" | "protection" | "daily" | "periodic" | "problem";

const PRODUCTS = catalogue.products as Product[];
const TREATMENTS = catalogue.treatments as Treatment[];
const BY_SLUG = new Map(PRODUCTS.map((p) => [p.slug, p]));
const PRICED = PRODUCTS.filter((p) => p.coverage.length > 0);

const MATERIALS = [
  "porcelain", "ceramic", "natural stone", "marble", "granite", "terracotta",
  "concrete", "terrazzo", "quartz", "wood", "LVT and vinyl",
];
const STAGES: { id: Stage; label: string; interval: string }[] = [
  { id: "after installation", label: "After installation", interval: "Once, when the tiler leaves" },
  { id: "protection", label: "Protection", interval: "Once, renewed when water stops beading" },
  { id: "daily", label: "Daily", interval: "Every cleaning round" },
  { id: "periodic", label: "Periodic", interval: "On the deep clean" },
  { id: "problem", label: "Stain problem", interval: "When the stain appears" },
];

const title = (s: string) => (s === "LVT and vinyl" ? s : s.charAt(0).toUpperCase() + s.slice(1));
const litres = (n: number) => (n >= 10 ? Math.round(n).toString() : n.toFixed(1).replace(/\.0$/, ""));

/** The guide prints a few figures per 750 ml bottle and a few in linear metres. */
const perUnit = (c: Coverage) => (c.note?.includes("750 ml") ? 0.75 : 1);
const unitWord = (c: Coverage) => (c.note?.includes("linear metres") ? "linear metres" : "m2");
function coverageWords(c: Coverage) {
  const span = Array.isArray(c.sqmPerLitre) ? `${c.sqmPerLitre[0]} to ${c.sqmPerLitre[1]}` : `${c.sqmPerLitre}`;
  const cap = c.note?.includes("up to") ? "up to " : "";
  return `${cap}${span} ${unitWord(c)} per ${c.note?.includes("750 ml") ? "750 ml bottle" : "litre"}`;
}
/** Litres for the area, lowest and highest end of the printed figure. */
function needed(c: Coverage, area: number, coats: number) {
  const span = Array.isArray(c.sqmPerLitre) ? c.sqmPerLitre : [c.sqmPerLitre, c.sqmPerLitre];
  const u = perUnit(c) * coats;
  return { low: (area / span[1]) * u, high: (area / span[0]) * u };
}
/** Pack volume in litres, read off the packaging line. */
function packVolume(pack: string) {
  const l = pack.match(/(\d+(?:[.,]\d+)?)\s*-?\s*litres?/i);
  if (l) return Number(l[1].replace(",", "."));
  const ml = pack.match(/(\d+)\s*ml/i);
  return ml ? Number(ml[1]) / 1000 : null;
}

export default function FilaCareRoutine() {
  const reduce = useReducedMotion();
  const [tab, setTab] = useState<"routine" | "quantity">("routine");
  const [material, setMaterial] = useState("marble");
  const [stage, setStage] = useState<Stage>("protection");
  const [slug, setSlug] = useState("mp90-eco-xtreme");
  const [surfaceIdx, setSurfaceIdx] = useState(0);
  const [area, setArea] = useState("120");
  const [coats, setCoats] = useState(1);

  const steps = useMemo(
    () =>
      STAGES.map((s) => {
        const rows = TREATMENTS.filter((t) => t.material === material && t.stage === s.id);
        return { ...s, rows, lead: rows[0] ? BY_SLUG.get(rows[0].product) : undefined };
      }),
    [material],
  );
  const idx = STAGES.findIndex((s) => s.id === stage);
  const cur = steps[idx];
  const filled = steps.filter((s) => s.rows.length).length;

  const product = BY_SLUG.get(slug) ?? PRICED[0];
  const cover = product.coverage[Math.min(surfaceIdx, product.coverage.length - 1)];
  const sqm = Number(area.replace(/[^\d.]/g, "")) || 0;
  const isProtector = product.category !== "cleaner";
  const sum = needed(cover, sqm, isProtector ? coats : 1);

  const pill = (on: boolean) =>
    `min-h-[2.75rem] rounded-full border px-4 py-2 font-manrope text-sm font-semibold transition-colors ${
      on ? "border-[#161925] bg-[#161925] text-white" : "border-[#161925]/15 text-[#161925]/75 hover:border-[#161925]/40"
    }`;
  const field =
    "mt-2 w-full min-h-[2.75rem] rounded-xl border border-[#161925]/15 bg-white px-4 font-manrope text-base text-[#161925] focus:border-[#406E8E] focus:outline-none";

  return (
    <section className="bg-white py-20 lg:py-28" aria-labelledby="fila-tool-h">
      <div className="mx-auto w-full max-w-[1400px] px-4 sm:px-6 lg:px-12">
        <p className="label-sh text-[#406E8E]">FILA Easy Guide, as a tool</p>
        <h2 id="fila-tool-h" className="mt-3 font-outfit text-3xl font-semibold leading-tight text-[#161925] sm:text-4xl lg:text-5xl">
          Build the FILA routine, then price the litres
        </h2>
        <p className="mt-4 max-w-2xl font-manrope text-lg leading-relaxed text-[#161925]/75">
          The whole FILA Easy Guide for the Middle East read into data: {PRODUCTS.length} products, the dilutions they
          print and the coverage for each surface. Pick the material to see the programme, then switch tab to turn an
          area into litres and packs.
        </p>

        <div role="tablist" aria-label="FILA tool" className="mt-8 flex flex-wrap gap-2">
          {([["routine", "Build the routine"], ["quantity", "How much do I need"]] as const).map(([id, label]) => (
            <button key={id} type="button" role="tab" aria-selected={tab === id} onClick={() => setTab(id)} className={pill(tab === id)}>
              {label}
            </button>
          ))}
        </div>

        {tab === "routine" ? (
          <div>
            <div className="mt-10">
              <p className="label-sh text-[#23395B]">Material</p>
              <div role="radiogroup" aria-label="Material" className="mt-3 flex flex-wrap gap-2">
                {MATERIALS.map((m) => (
                  <button key={m} type="button" role="radio" aria-checked={material === m} onClick={() => setMaterial(m)} className={pill(material === m)}>
                    {title(m)}
                  </button>
                ))}
              </div>
            </div>

            <div className="mt-12 grid gap-10 lg:grid-cols-[1.618fr_1fr]">
              <ol className="relative" aria-label="FILA programme">
                <div aria-hidden="true" className="absolute left-[11px] top-3 bottom-3 w-px bg-[#161925]/10" />
                <motion.div aria-hidden="true" className="absolute left-[11px] top-3 w-px origin-top bg-[#406E8E]" initial={false} animate={{ height: `calc(${(idx / (STAGES.length - 1)) * 100}% - 1.5rem)` }} transition={reduce ? { duration: 0 } : { type: "spring", stiffness: 120, damping: 22 }} />
                {steps.map((s, i) => {
                  const on = i === idx;
                  const done = i <= idx;
                  return (
                    <li key={s.id} className="relative pb-8 pl-10 last:pb-0">
                      <button type="button" onClick={() => setStage(s.id)} aria-current={on ? "step" : undefined} className="group block w-full text-left">
                        <motion.span aria-hidden="true" className="absolute left-0 top-1 flex h-6 w-6 items-center justify-center rounded-full border-2 bg-white" initial={false} animate={{ borderColor: done ? "#406E8E" : "rgba(22,25,37,0.2)", scale: on ? 1.15 : 1 }} transition={{ duration: reduce ? 0 : 0.2 }}>
                          <motion.span className="h-2.5 w-2.5 rounded-full bg-[#406E8E]" initial={false} animate={{ scale: done ? 1 : 0 }} transition={{ duration: reduce ? 0 : 0.2 }} />
                        </motion.span>
                        <span className="label-sh text-[#406E8E]">{s.label}</span>
                        <span className={`mt-1 block font-outfit text-2xl font-semibold leading-tight transition-colors ${on ? "text-[#161925]" : "text-[#161925]/55 group-hover:text-[#161925]"}`}>
                          {s.lead ? s.lead.name : "Not in this guide"}
                        </span>
                        <span className="mt-1 block font-manrope text-sm text-[#23395B]">
                          {s.rows[0] ? `${s.rows[0].dilution} · ${s.interval}` : `The guide names no product for ${title(material)} at this step`}
                        </span>
                      </button>
                    </li>
                  );
                })}
              </ol>

              <AnimatePresence mode="wait">
                <motion.article key={material + stage} initial={reduce ? false : { opacity: 0, y: 10 }} animate={{ opacity: 1, y: 0 }} exit={reduce ? undefined : { opacity: 0 }} transition={{ duration: 0.25 }} className="h-fit rounded-3xl bg-[#161925] p-7 text-white sm:p-9 lg:sticky lg:top-24">
                  <p className="label-sh text-[#BFD7EA]">{title(material)}, {cur.label.toLowerCase()}</p>
                  {cur.lead && cur.rows[0] ? (
                    <>
                      <h3 className="mt-3 font-outfit text-3xl font-semibold leading-tight sm:text-4xl">{cur.lead.name}</h3>
                      <p className="mt-2 font-manrope text-sm text-[#BFD7EA]">{cur.lead.purpose}, page {cur.lead.page} of the guide</p>
                      <p className="mt-4 font-manrope leading-relaxed text-white/80">{cur.rows[0].note}</p>
                      <dl className="mt-7 grid grid-cols-1 gap-6 border-t border-white/10 pt-6 sm:grid-cols-2">
                        {[["Dilution", cur.rows[0].dilution], ["Interval", cur.interval]].map(([k, v]) => (
                          <div key={k}>
                            <dd className="font-outfit text-xl font-semibold leading-tight text-[#F3DFC1]">{v}</dd>
                            <dt className="label-sh mt-2 text-white/60">{k}</dt>
                          </div>
                        ))}
                      </dl>
                      {cur.rows.length > 1 && (
                        <p className="mt-6 font-manrope text-sm text-white/70">
                          Also listed for {title(material)} at this step: {cur.rows.slice(1).map((r) => BY_SLUG.get(r.product)?.name).join(", ")}.
                        </p>
                      )}
                      {cur.lead.coverage.length > 0 && (
                        <button type="button" onClick={() => { setSlug(cur.lead!.slug); setSurfaceIdx(0); setTab("quantity"); }} className="mt-7 inline-flex min-h-[2.75rem] items-center rounded-full bg-[#F3DFC1] px-5 font-manrope text-sm font-semibold text-[#161925] transition-opacity hover:opacity-90">
                          Work out the litres
                        </button>
                      )}
                    </>
                  ) : (
                    <>
                      <h3 className="mt-3 font-outfit text-3xl font-semibold leading-tight sm:text-4xl">Nothing printed for this step</h3>
                      <p className="mt-4 font-manrope leading-relaxed text-white/80">
                        The FILA Easy Guide does not name a product for {title(material)} at the {cur.label.toLowerCase()} step. Send the
                        surface and the problem to the Lapiz Blue technical desk and we will come back with the FILA line and its data sheet.
                      </p>
                    </>
                  )}
                </motion.article>
              </AnimatePresence>
            </div>
            <p className="mt-8 font-manrope text-sm text-[#23395B]">
              {filled === STAGES.length ? "All five steps are covered" : `${filled} of the five steps are covered`} for {title(material)}. Dilution is parts of product to parts of
              water, exactly as the guide prints it. The FILA technical data sheet governs the dilution, the dwell time
              and the yield quoted on site.
            </p>
          </div>
        ) : (
          <div className="mt-10 grid gap-10 lg:grid-cols-[1.618fr_1fr]">
            <div>
              <div className="grid gap-6 sm:grid-cols-2">
                <label className="block">
                  <span className="label-sh text-[#23395B]">Product</span>
                  <select className={field} value={slug} onChange={(e) => { setSlug(e.target.value); setSurfaceIdx(0); }}>
                    {(["cleaner", "protector", "finish"] as const).map((c) => (
                      <optgroup key={c} label={c === "cleaner" ? "Cleaners" : c === "protector" ? "Protectors" : "Finishing"}>
                        {PRICED.filter((p) => p.category === c).map((p) => (
                          <option key={p.slug} value={p.slug}>{p.name}</option>
                        ))}
                      </optgroup>
                    ))}
                  </select>
                </label>
                <label className="block">
                  <span className="label-sh text-[#23395B]">Surface, as the guide lists it</span>
                  <select className={field} value={surfaceIdx} onChange={(e) => setSurfaceIdx(Number(e.target.value))}>
                    {product.coverage.map((c, i) => (
                      <option key={c.surface + i} value={i}>{c.surface}, {coverageWords(c)}</option>
                    ))}
                  </select>
                </label>
                <label className="block">
                  <span className="label-sh text-[#23395B]">Area in {unitWord(cover)}</span>
                  <input className={field} type="number" inputMode="decimal" min={0} value={area} onChange={(e) => setArea(e.target.value)} />
                </label>
                {isProtector ? (
                  <div>
                    <p className="label-sh text-[#23395B]">Coats</p>
                    <div role="radiogroup" aria-label="Coats" className="mt-2 flex flex-wrap gap-2">
                      {[1, 2, 3].map((n) => (
                        <button key={n} type="button" role="radio" aria-checked={coats === n} onClick={() => setCoats(n)} className={pill(coats === n)}>
                          {n} {n === 1 ? "coat" : "coats"}
                        </button>
                      ))}
                    </div>
                  </div>
                ) : (
                  <div>
                    <p className="label-sh text-[#23395B]">Dilution printed for this product</p>
                    <p className="mt-2 font-manrope text-base text-[#161925]">
                      {product.dilutions.length
                        ? product.dilutions.map((d) => `${d.ratio} for ${d.label.toLowerCase()}`).join(". ") + "."
                        : "The guide prints no dilution for this product. Use it as supplied."}
                    </p>
                  </div>
                )}
              </div>

              <div className="mt-8 rounded-2xl bg-[#F6F8FA] p-6 sm:p-8">
                <p className="label-sh text-[#406E8E]">The sum on screen</p>
                <p className="mt-3 font-manrope text-base leading-relaxed text-[#161925]">
                  {sqm || 0} {unitWord(cover)} divided by {coverageWords(cover)}
                  {isProtector ? `, times ${coats} ${coats === 1 ? "coat" : "coats"}` : ""}, for {cover.surface.toLowerCase()}.
                  Packs are rounded up at the high end of the figure, because a part pack cannot be bought. Allow for
                  wastage on the quotation, not here.
                </p>
              </div>
            </div>

            <motion.aside key={slug + surfaceIdx + area + coats} initial={reduce ? false : { opacity: 0, y: 10 }} animate={{ opacity: 1, y: 0 }} transition={{ duration: 0.25 }} className="h-fit rounded-3xl bg-[#161925] p-7 text-white sm:p-9 lg:sticky lg:top-24">
              <p className="label-sh text-[#BFD7EA]">{product.name}, page {product.page}</p>
              <p className="mt-3 font-outfit text-4xl font-semibold leading-none text-[#F3DFC1] sm:text-5xl">
                {sum.high <= 0 ? "0" : litres(sum.low) === litres(sum.high) ? litres(sum.high) : `${litres(sum.low)} to ${litres(sum.high)}`}
              </p>
              <p className="mt-2 font-manrope text-sm text-white/70">
                litres for {sqm || 0} {unitWord(cover)}, {cover.surface.toLowerCase()}
                {isProtector ? `, ${coats} ${coats === 1 ? "coat" : "coats"}` : ""}
              </p>
              {Array.isArray(cover.sqmPerLitre) && sum.high > 0 && (
                <p className="mt-3 font-manrope text-sm text-[#BFD7EA]">
                  The guide prints a range, so between {litres(sum.low)} and {litres(sum.high)} litres.
                </p>
              )}
              <dl className="mt-7 space-y-4 border-t border-white/10 pt-6">
                {product.packSizes.map((pack) => {
                  const v = packVolume(pack);
                  return (
                    <div key={pack} className="flex items-baseline justify-between gap-4">
                      <dt className="font-manrope text-sm text-white/70">{pack}</dt>
                      <dd className="shrink-0 font-outfit text-xl font-semibold text-white">
                        {v && sum.high > 0 ? `${Math.ceil(sum.high / v)} ${Math.ceil(sum.high / v) === 1 ? "pack" : "packs"}` : "on request"}
                      </dd>
                    </div>
                  );
                })}
              </dl>
              <p className="mt-6 font-manrope text-xs leading-relaxed text-white/60">
                Figures are the coverage printed in the FILA Easy Guide for the Middle East, 06.2023. The FILA technical
                data sheet for the product governs the yield, the dilution and the application on site.
              </p>
            </motion.aside>
          </div>
        )}

        <p className="mt-10 border-t border-[#161925]/10 pt-6 font-manrope text-sm text-[#23395B]">
          <a href="/documents/fila-easy-guide-2023.pdf" target="_blank" rel="noopener" className="font-semibold text-[#406E8E] underline underline-offset-4">
            The full FILA Easy Guide, {PRODUCTS.length} products with dilutions and coverage
          </a>{" "}
          (PDF). Every dilution and coverage figure in this tool is read from that guide.
        </p>
      </div>
    </section>
  );
}
